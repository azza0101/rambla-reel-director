#!/bin/bash
# Uses only system tools. Never changes Gatekeeper, quarantine or global permissions.
set -euo pipefail
BASE="$(cd "$(dirname "$0")/.." && pwd)"
ROOT='/Library/Application Support/Blackmagic Design/DaVinci Resolve/Workflow Integration Plugins'
SDK='/Library/Application Support/Blackmagic Design/DaVinci Resolve/Developer/Workflow Integrations/Examples/SamplePlugin/WorkflowIntegration.node'
QUIET=0
while [ "$#" -gt 0 ]; do
 case "$1" in
  --plugin-root) ROOT="$2"; shift 2;;
  --sdk) SDK="$2"; shift 2;;
  --quiet) QUIET=1; shift;;
  *) printf 'Opzione sconosciuta: %s\n' "$1" >&2; exit 1;;
 esac
done
case "$ROOT" in /*) ;; *) echo 'Destinazione assoluta richiesta'; exit 1;; esac
no_links() { local cursor="$1"; while [ "$cursor" != / ] && [ -n "$cursor" ]; do [ ! -L "$cursor" ] || { echo 'Link simbolico non consentito' >&2; return 1; }; cursor="$(dirname "$cursor")"; done; }
no_links "$ROOT"; no_links "$SDK"; no_links "$BASE"
[ -f "$SDK" ] || { echo 'SDK Resolve Studio non trovato.' >&2; exit 1; }
FILES=(main.js preload.js resolve_adapter.js core.js session.js updater.js index.html style.css renderer.js package.json manifest.xml)
for file in "${FILES[@]}"; do no_links "$BASE/plugin/$file"; [ -f "$BASE/plugin/$file" ] || exit 1; done
# Manifest generated by the release builder; enforce exact names before shasum.
[ "$(wc -l < "$BASE/install/checksums.sha256" | tr -d ' ')" = "${#FILES[@]}" ] || exit 1
for file in "${FILES[@]}"; do
 expected="$(awk -v name="$file" '$2 == name {print $1}' "$BASE/install/checksums.sha256")"
 actual="$(shasum -a 256 "$BASE/plugin/$file")"; actual="${actual%% *}"
 [ "$expected" = "$actual" ] || { echo "File danneggiato: $file" >&2; exit 1; }
done
if [ "$EUID" -ne 0 ] && { [ ! -d "$ROOT" ] || [ ! -w "$ROOT" ]; }; then
 echo 'Autorizzazione amministratore per la sola cartella del plugin RAMBLA SRT.'
 exec /usr/bin/sudo /bin/bash "$BASE/install/install-mac.sh" --plugin-root "$ROOT" --sdk "$SDK"
fi
mkdir -p "$ROOT"
ROOT="$(cd "$ROOT" && pwd -P)"
TARGET="$ROOT/com.rambla.srt"
no_links "$TARGET"
INCOMING="$(sed -n 's/.*"version":"\([0-9.]*\)".*/\1/p' "$BASE/plugin/package.json")"
[ -n "$INCOMING" ] || exit 1
if [ -e "$TARGET" ]; then
 [ -d "$TARGET" ] && [ -f "$TARGET/package.json" ] || exit 1
 [ -z "$(find "$TARGET" -type l -print -quit)" ] || { echo 'Link nel plugin esistente'; exit 1; }
 grep -q '"name":"rambla-srt"' "$TARGET/package.json" || exit 1
 CURRENT="$(sed -n 's/.*"version":"\([0-9.]*\)".*/\1/p' "$TARGET/package.json")"
 if awk -v a="$CURRENT" -v b="$INCOMING" 'BEGIN{split(a,x,".");split(b,y,".");for(i=1;i<=3;i++){if(x[i]+0>y[i]+0)exit 0;if(x[i]+0<y[i]+0)exit 1}exit 1}'; then echo 'Downgrade annullato'; exit 1; fi
fi
STAGE="$(mktemp -d "$ROOT/.com.rambla.srt-stage-XXXXXX")"
BACKUP_ROOT="$(dirname "$ROOT")/RAMBLA SRT Install Backups"
no_links "$BACKUP_ROOT"
BACKUP="$BACKUP_ROOT/$(date +%Y%m%d-%H%M%S)-$$"
cleanup(){ case "$STAGE" in "$ROOT"/.com.rambla.srt-stage-*) if [ ! -L "$STAGE" ] && [ -d "$STAGE" ]; then rm -rf -- "$STAGE"; fi;; esac; return 0; }
trap cleanup EXIT
for file in "${FILES[@]}"; do cp "$BASE/plugin/$file" "$STAGE/$file"; cmp -s "$BASE/plugin/$file" "$STAGE/$file"; done
cp "$SDK" "$STAGE/WorkflowIntegration.node"; cmp -s "$SDK" "$STAGE/WorkflowIntegration.node"
chmod 755 "$STAGE"; chmod 644 "$STAGE/"*
# Keep ownership with the signed-in user so code-only updates need no sudo.
if [ "$EUID" -eq 0 ] && [ -n "${SUDO_UID:-}" ] && [ -n "${SUDO_GID:-}" ]; then chown -R "$SUDO_UID:$SUDO_GID" "$STAGE"; fi
MOVED=0
if [ -d "$TARGET" ]; then mkdir -p "$BACKUP_ROOT"; mv "$TARGET" "$BACKUP"; MOVED=1; fi
if ! mv "$STAGE" "$TARGET"; then [ "$MOVED" -eq 0 ] || mv "$BACKUP" "$TARGET"; exit 1; fi
echo "RAMBLA SRT $INCOMING installato. Workspace > Workflow Integrations > RAMBLA SRT."
echo 'Prima registrazione: può essere necessario riavviare Resolve. AutoCut e Utility sono invariati.'
if [ "$QUIET" -eq 0 ] && command -v osascript >/dev/null; then /usr/bin/osascript -e 'display dialog "RAMBLA SRT installato. Apri Workspace > Workflow Integrations > RAMBLA SRT. La prima registrazione può richiedere il riavvio di Resolve." buttons {"OK"} default button "OK" with title "RAMBLA SRT"'; fi
exit 0
